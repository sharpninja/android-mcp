using System.Text;
using System.Text.Json;
using AndroidMcp.BuildTool.Core;

namespace AndroidMcp.BuildTool.Documentation;

/// <summary>Pure checked-in Gradle projection from the two existing C# metadata authorities.</summary>
public sealed class NativeDesignGradleProjection(ICanonicalJson canonical,IArtifactReceiptVerifier verifier):IDesignGradleProjection
{
    // Existing projection and immutable generation runtime remain the only
    // serialization and commit authorities. No project inputs or tools are read.
    public ArtifactGenerationRecipe CreateRecipe(DesignStageManifest stages,OperationDefinition operation)=>new([],inputs=>
    {
        if(inputs.Count!=0)throw new ArgumentException("Gradle projection accepts no source artifacts",nameof(inputs));
        var projection=Render(stages,operation);
        IReadOnlyList<Artifact> artifacts=[projection.Descriptor,projection.BuildScript];
        return new(artifacts.Select(artifact=>artifact.RelativePath).ToArray(),token=>
        {
            token.ThrowIfCancellationRequested();
            return Task.FromResult(artifacts);
        });
    });

    public DesignGradleProjection Render(DesignStageManifest stages,OperationDefinition operation)
    {
        var parameters=operation.RequiredParameters.Select(name=>(Name:name,Required:true))
            .Concat(operation.OptionalParameters.Select(name=>(Name:name,Required:false)))
            .Where(parameter=>parameter.Name is not ("design-aliases" or "design-registry-sha256"))
            .Select(parameter=>new{name=parameter.Name,property="nuke"+string.Concat(parameter.Name.Split('-').Select(word=>char.ToUpperInvariant(word[0])+word[1..])),required=parameter.Required}).ToArray();
        var descriptor=new{schema_version=1,registry_sha256=stages.Sha256,target=operation.Key.Category.ToString(),operation=operation.Key.Operation.ToString(),
            alias_parameter="design-aliases",registry_parameter="design-registry-sha256",aliases=stages.Metadata.Aliases.Select(alias=>alias.Name).ToArray(),parameters};
        return new(new("tooling/nuke-design-stages.json",canonical.Serialize(JsonSerializer.SerializeToElement(descriptor)),"application/json"),
            new("build.gradle.kts",Encoding.UTF8.GetBytes(Script),"text/plain"));
    }
    public IReadOnlyList<DesignGradleProjectionIssue> Check(DesignStageManifest stages,OperationDefinition operation,IReadOnlyList<Artifact> retainedProjection)
    {
        var expected=Render(stages,operation);Artifact[] files=[expected.Descriptor,expected.BuildScript];
        if(retainedProjection.Count!=files.Length||retainedProjection.Select(artifact=>artifact.RelativePath).Distinct(StringComparer.Ordinal).Count()!=files.Length
            ||!retainedProjection.Select(artifact=>artifact.RelativePath).Order(StringComparer.Ordinal).SequenceEqual(files.Select(artifact=>artifact.RelativePath).Order(StringComparer.Ordinal),StringComparer.Ordinal))
            return [new("GRADLE_PROJECTION_SET","")];
        return files.Where(artifact=>!verifier.Matches(retainedProjection.Single(retained=>retained.RelativePath==artifact.RelativePath),verifier.Describe(artifact)))
            .Select(artifact=>new DesignGradleProjectionIssue("STALE_GRADLE_PROJECTION",artifact.RelativePath)).ToArray();
    }
    private const string Script="""
import groovy.json.JsonSlurper

plugins { base }

// Generated by the C# NUKE application. Alias and parameter metadata live in its descriptor.
val nukeDesignDescriptor = JsonSlurper().parse(file("tooling/nuke-design-stages.json")) as Map<*, *>
val nukeDesignAliases = (nukeDesignDescriptor["aliases"] as List<*>).map { it as String }
check(nukeDesignAliases.isNotEmpty() && nukeDesignAliases.distinct().size == nukeDesignAliases.size) { "Invalid NUKE alias descriptor" }

val nukeDesignCompatibility by tasks.registering(Exec::class) {
    group = "documentation"
    description = "Delegate the selected design alias union to the C# NUKE application"
    isIgnoreExitValue = false
    doFirst {
        fun requiredProperty(name: String): String = providers.gradleProperty(name).orNull
            ?.takeIf { it.isNotBlank() } ?: error("Supply -P$name before executing a design alias")
        val nativeHost = File(requiredProperty("nukeDotnetHost"))
        check(nativeHost.isAbsolute && nativeHost.isFile) { "nukeDotnetHost must identify the existing native dotnet host" }
        val buildProject = File(requiredProperty("nukeProject")).canonicalFile
        check(buildProject.isFile) { "nukeProject must identify the C# NUKE build project" }
        val selected = gradle.taskGraph.allTasks.filter { candidate ->
            candidate.project == project && candidate.name in nukeDesignAliases
        }.map { it.name }.distinct().sorted()
        check(selected.isNotEmpty()) { "Select at least one declared design alias" }
        val arguments = mutableListOf(nativeHost.absolutePath, "run", "--no-restore", "--project", buildProject.absolutePath,
            "--", "--root", buildProject.parentFile.absolutePath,
            "--dotnet-host", nativeHost.absolutePath,
            "--target", nukeDesignDescriptor["target"] as String,
            "--operation", nukeDesignDescriptor["operation"] as String,
            "--" + nukeDesignDescriptor["alias_parameter"], selected.joinToString(","),
            "--" + nukeDesignDescriptor["registry_parameter"], nukeDesignDescriptor["registry_sha256"] as String)
        (nukeDesignDescriptor["parameters"] as List<*>).forEach { value ->
            val parameter = value as Map<*, *>
            val property = parameter["property"] as String
            val supplied = providers.gradleProperty(property).orNull?.takeIf { it.isNotBlank() }
            if (parameter["required"] == true) check(supplied != null) { "Supply -P$property" }
            if (supplied != null) arguments.addAll(listOf("--" + parameter["name"], supplied))
        }
        workingDir(projectDir)
        commandLine(arguments)
    }
}

nukeDesignAliases.forEach { alias ->
    tasks.register(alias) {
        group = "documentation"
        description = "Delegate $alias through the authoritative NUKE stage planner"
        dependsOn(nukeDesignCompatibility)
    }
}
"""+"\n";
}
