// Faults are injected at the shared store/lease boundary. The service never
// sees a different contract assertion or fixture oracle than the mock gate.
public sealed class StageMemoryStore(string name,List<string> events):IArtifactStore
{
    public Dictionary<string,byte[]> Data { get; }=new(StringComparer.Ordinal);
    public Dictionary<string,int> Reads { get; }=new(StringComparer.Ordinal);
    public List<string> Writes { get; }=[];
    public int WriteAttempts { get; private set; }
    public Action<string,int>? BeforeRead { get; set; }
    public Action<string,int>? BeforeWrite { get; set; }
    public Action<string,int>? AfterWrite { get; set; }
    public Task<ReadOnlyMemory<byte>> ReadAsync(string path,CancellationToken token=default)
    {
        token.ThrowIfCancellationRequested();
        var count=Reads.GetValueOrDefault(path)+1;Reads[path]=count;
        events.Add("read:"+name+":"+path);BeforeRead?.Invoke(path,count);
        if(!Data.TryGetValue(path,out var bytes))throw new FileNotFoundException(path);
        return Task.FromResult<ReadOnlyMemory<byte>>(bytes.ToArray());
    }
    public Task<StoredArtifact> WriteAsync(Artifact artifact,CancellationToken token=default)
    {
        token.ThrowIfCancellationRequested();WriteAttempts++;
        BeforeWrite?.Invoke(artifact.RelativePath,WriteAttempts);
        if(Data.TryGetValue(artifact.RelativePath,out var old) && !old.AsSpan().SequenceEqual(artifact.Bytes.Span))throw new IOException("Conflicting immutable artifact retained");
        Data[artifact.RelativePath]=artifact.Bytes.ToArray();Writes.Add(artifact.RelativePath);
        events.Add("write:"+name+":"+artifact.RelativePath);AfterWrite?.Invoke(artifact.RelativePath,WriteAttempts);
        return Task.FromResult(new StoredArtifact(artifact.RelativePath,PublicationTestData.Hash(artifact.Bytes),artifact.Bytes.Length,artifact.MediaType));
    }
}
public sealed class StageTestLease: IArtifactLeaseProvider
{
    public bool Released { get; private set; }=true;
    public ValueTask<IAsyncDisposable> AcquireAsync(string scope,CancellationToken token=default)
    {token.ThrowIfCancellationRequested();Released=false;return ValueTask.FromResult<IAsyncDisposable>(new Lease(this));}
    private sealed class Lease(StageTestLease owner):IAsyncDisposable
    {public ValueTask DisposeAsync(){owner.Released=true;return ValueTask.CompletedTask;}}
}
public sealed class StageTestClock:IClock { public DateTimeOffset Now=>StageContractCases.Time; }
public sealed class NativeStageCaseProvider:IStageCaseProvider
{
    // Independent pinned manifest schema, not generated by PublicationStager.
    private static byte[] ExpectedManifest(StageRequest request)=>new CanonicalJson().Serialize(JsonSerializer.SerializeToUtf8Bytes(new
    {
        schema_version=1,generation=request.GenerationId,policy_sha256=PublicationTestData.Hash(request.Policy),
        files=request.Files.OrderBy(x=>x.DestinationPath,StringComparer.Ordinal).Select(x=>new{path=x.DestinationPath,sha256=x.Sha256,length=x.Length,media_type=x.MediaType}).ToArray()
    }));
    public async Task<StageObservation> RunAsync(StageCase test)
    {
        var events=new List<string>();var source=new StageMemoryStore("source",events);var output=new StageMemoryStore("output",events);
        source.Data["input/a"]=PublicationTestData.Bytes("abc");source.Data["input/b"]=PublicationTestData.Bytes("def");
        output.Data["unrelated/original"]=PublicationTestData.Bytes("retain unrelated original");
        var request=PublicationTestData.Request();var files=request.Files.ToArray();using var cancellation=new CancellationTokenSource();
        switch(test.Fault)
        {
            case "bad-last-source":source.Data["input/b"]=PublicationTestData.Bytes("bad");break;
            case "existing-conflict":output.Data[PublicationTestData.Output("b.md")]=PublicationTestData.Bytes("existing");break;
            case "missing-last-source":source.Data.Remove("input/b");break;
            case "duplicate-target":files[1]=files[1] with{DestinationPath="a.md"};break;
            case "unsafe-target":files[1]=files[1] with{DestinationPath="../escape"};break;
            case "not-allowed":files[1]=files[1] with{DestinationPath="private.txt"};break;
            case "race-conflict":output.BeforeWrite=(path,count)=>{if(count==2){output.Data[path]=PublicationTestData.Bytes("race winner");throw new IOException("External creator won");}};break;
            case "cancel-after-first":output.AfterWrite=(_,count)=>{if(count==1)cancellation.Cancel();};break;
            case "source-changed-at-commit":source.BeforeRead=(path,count)=>{if(path=="input/a" && count==2)source.Data[path]=PublicationTestData.Bytes("externally changed");};break;
            case "output-changed-at-commit":output.BeforeRead=(path,count)=>{if(path==PublicationTestData.Output("a.md") && count==2)output.Data[path]=PublicationTestData.Bytes("externally changed");};break;
            case "identical-existing":output.Data[PublicationTestData.Output("a.md")]=PublicationTestData.Bytes("abc");break;
            case "old-marker-conflict":output.Data[PublicationTestData.Commit]=PublicationTestData.Bytes("different generation");break;
            case "unsafe-generation":request=request with{GenerationId="../escape"};break;
            case "invalid-pin":files[0]=files[0] with{Sha256="not-a-pin"};break;
            case "unsafe-source":files[0]=files[0] with{SourcePath="../escape"};break;
            case "committed-resume":
            case "committed-output-missing":
                output.Data[PublicationTestData.Output("a.md")]=PublicationTestData.Bytes("abc");
                if(test.Fault=="committed-resume")output.Data[PublicationTestData.Output("b.md")]=PublicationTestData.Bytes("def");
                output.Data[PublicationTestData.Commit]=ExpectedManifest(request);break;
            case "cancel-before-copy":cancellation.Cancel();break;
            case "wrong-source-size":files[1]=files[1] with{Length=4};break;
        }
        request=request with{Files=files};
        var originals=output.Data.ToDictionary(x=>x.Key,x=>x.Value.ToArray(),StringComparer.Ordinal);
        var lease=new StageTestLease();
        var service=new PublicationStager(source,output,lease,new StageTestClock(),new PublicationChecker(new CanonicalJson()),new CanonicalJson());
        var result=await service.StageAsync(request,cancellation.Token);
        var firstCopy=events.FindIndex(x=>x.StartsWith("write:output:",StringComparison.Ordinal));
        var preflight=firstCopy<0 || request.Files.All(x=>events.Take(firstCopy).Contains("read:source:"+x.SourcePath));
        var markerLast=!output.Writes.Contains(PublicationTestData.Commit) || output.Writes.Last()==PublicationTestData.Commit;
        var retained=originals.All(x=>output.Data.TryGetValue(x.Key,out var bytes) && bytes.AsSpan().SequenceEqual(x.Value));
        if(test.Fault=="race-conflict")retained &= output.Data[PublicationTestData.Output("b.md")].AsSpan().SequenceEqual(PublicationTestData.Bytes("race winner"));
        return new(result,output.Writes.ToArray(),source.WriteAttempts==0,preflight,markerLast,retained,lease.Released);
    }
}
